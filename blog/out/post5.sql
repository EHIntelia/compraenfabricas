## Por qué tomar un curso antes de importar de China

Puedes aprender solo con videos gratis. Yo empecé sin nada. Pero aprender solo tiene un costo: **los errores se pagan con tu dinero**. Un pago a una fábrica falsa, una mercancía atorada en la aduana por no tener la NOM o un producto sin margen te pueden costar mucho más que cualquier curso.

Un buen curso te da tres cosas que lo gratis casi nunca tiene:

- **Orden.** El proceso completo, en el orden correcto.
- **A quién preguntarle.** Tu caso es distinto al del video.
- **Atajos.** Fábricas ya revisadas, plantillas, cálculos listos.

## Los 7 criterios para elegir un curso para importar de China

1. **Precio.** ¿Lo recuperas con tu primera importación?
2. **En vivo o grabado.** ¿Puedes preguntar o solo ver?
3. **¿El que enseña importa de verdad?** ¿Tiene negocios funcionando o solo vende cursos?
4. **¿Cubre el proceso completo?** Producto, fábrica, validación, pago, envío, aduana, impuestos, NOM.
5. **¿Incluye proveedores?** Encontrar una fábrica confiable es lo más difícil.
6. **¿Hay comunidad?** Gente en el mismo camino para compartir lo que funciona.
7. **¿Qué soporte hay después?** ¿Te quedas solo cuando terminas?

