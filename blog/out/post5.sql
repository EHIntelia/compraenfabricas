## Qué temas debe cubrir un buen curso para importar de China

Antes de pagar, revisa el temario. Si le falta alguno de estos puntos, te va a tocar aprenderlo a golpes:

1. **Cómo elegir un producto con margen**, con la cuenta de costo puesto en México.
2. **Cómo encontrar fábricas reales**, no revendedores con sobreprecio.
3. **Cómo validar que la fábrica es confiable** antes de mandarle dinero.
4. **Cómo negociar** precio, pedido mínimo y tiempos, y cómo pedir muestras.
5. **Cómo pagar a China** sin que te estafen.
6. **Incoterms** explicados en simple (EXW, FOB, CIF, DDP).
7. **Envío aéreo vs. marítimo** y cómo cotizarlo.
8. **Aduana en México:** padrón de importadores, agente aduanal, pedimento, fracción arancelaria, NOM y etiquetado.
9. **Impuestos**, incluidos los aumentos de aranceles de 2026 para productos de China.
10. **Cómo vender** lo que traes, porque importar sin vender no es negocio.

La [clase en vivo para aprender a importar de China](/clase) cubre todo ese recorrido en una sola sesión, de la fábrica hasta tu puerta.

