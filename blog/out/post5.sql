## Errores al elegir un curso para importar

1. **Comprar por la promesa de "hazte rico".** Importar es un negocio, no un truco.
2. **No revisar quién enseña.** Busca negocios reales, años y gente asesorada, no seguidores.
3. **Pagar caro por información que está gratis.** Lo que vale es la experiencia y el soporte.
4. **Elegir solo por precio.** Un curso barato que no te deja preguntar puede salirte caro en errores.
5. **No preguntar qué pasa después.** ¿Hay comunidad? ¿Hay a quién escribirle?

## Mi recomendación honesta

Si apenas vas a empezar, primero entiende si importar es para ti: lee la guía, haz tus números con un producto real y decide. Si ya quieres hacerlo, toma algo que te deje **preguntar** y que te dé **atajos reales**, como fábricas revisadas.

Y una cosa que casi ningún curso te dice: elige bien el producto con el que vas a practicar. Hay productos que perdonan los errores del principiante (ligeros, chicos, con buen margen) y otros que no. La joyería, por ejemplo, es de los que más perdonan. Lo explico en [qué productos importar de China para revender](/blog/productos-para-importar-de-china).

