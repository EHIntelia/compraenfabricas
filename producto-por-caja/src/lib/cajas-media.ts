export function mediaCaja(c: Caja): CajaMedia {
  return MEDIA[c.name] ?? {};
}

/** Foto principal (photos[0]); si no hay, primera imagen del catálogo; si no, undefined (placeholder). */
export function fotoCaja(c: Caja): string | undefined {
  return mediaCaja(c).photos?.[0] ?? imagenesCatalogo(c.code)[0];
}

/** Video principal de la caja (src/assets/cajas/videos/). */
export function videoCaja(c: Caja): string | undefined {
  return mediaCaja(c).videos?.[0];
}

/** Todas las fotos de la caja, sin repetir. */
export function galeriaCaja(c: Caja): string[] {
  const m = mediaCaja(c);
  return [...new Set([...(m.photos ?? []), ...(m.extraImages ?? []), ...imagenesCatalogo(c.code)])];
}

/**
 * Imagen 1200x630 para compartir (public/og/producto/<id>.jpg).
 * Al agregar una caja nueva: sube su imagen a public/og/producto/ y agrega el id aquí.
 * Si no está en la lista se usa la foto principal (1280x720).
 */
const OG_LISTOS = new Set([
  "CF-001", "CF-005", "CF-006", "CF-007", "CF-008", "CF-011", "CF-012", "CF-017", "CF-018", "CF-020",
  "CF-021", "CF-022", "CF-023", "CF-024", "CF-027", "CF-037", "CF-038", "CF-039", "SAG11", "SAG20",
]);

export function ogImagenCaja(c: Caja): { url: string; width: number; height: number } | undefined {
  const id = cajaId(c);
  if (OG_LISTOS.has(id)) return { url: `/og/producto/${id}.jpg`, width: 1200, height: 630 };
  const foto = fotoCaja(c);
  return foto ? { url: foto, width: 1280, height: 720 } : undefined;
}
